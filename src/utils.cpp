// Debug output
void debug_print_sensors() {
  sensors_data_t* data = sensors_get_data();
  
  Serial.print("[DEBUG] Tверх=");
  if (data->aht10_top_valid) {
    Serial.print(data->temp_top, 1);
  } else {
    Serial.print("ERR");
  }
  
  Serial.print(" Tниз=");
  if (data->aht10_bottom_valid) {
    Serial.print(data->temp_bottom, 1);
  } else {
    Serial.print("ERR");
  }
  
  Serial.print(" Hверх=");
  if (data->aht10_top_valid) {
    Serial.print((int)data->humidity_top);
  } else {
    Serial.print("ERR");
  }
  
  Serial.print(" Hниз=");
  if (data->aht10_bottom_valid) {
    Serial.print((int)data->humidity_bottom);
  } else {
    Serial.print("ERR");
  }
  
  Serial.print(" Tбак=");
  if (data->ds18b20_valid) {
    Serial.print(data->temp_tank, 1);
  } else {
    Serial.print("ERR");
  }
  
  Serial.print(" Tср=");
  Serial.print(data->temp_avg, 1);
  
  Serial.print(" Hср=");
  Serial.print((int)data->humidity_avg);
  
  Serial.print(" dT/dt=");
  Serial.print(sensors_get_temp_change_rate(), 2);
  
  Serial.println();
}

// CRC8 calculation
uint8_t crc8(uint8_t* data, uint8_t length) {
  uint8_t crc = 0;
  for (uint8_t i = 0; i < length; i++) {
    crc = CRC8_TABLE[crc ^ data[i]];
  }
  return crc;
}
